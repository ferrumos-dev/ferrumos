use core::arch::{asm, global_asm};
use core::cell::UnsafeCell;
use core::mem::size_of;
use core::sync::atomic::{AtomicBool, AtomicU64, Ordering};

use super::{PIT_DIVISOR, PIT_INPUT_HZ};
use crate::arch::x86_64::cpu;
use crate::arch::x86_64::io::write_u8;
use crate::kernel::interrupts::TickSnapshot;

const TIMER_VECTOR: u64 = 32;
const MASTER_COMMAND: u16 = 0x20;
const MASTER_DATA: u16 = 0x21;
const SLAVE_COMMAND: u16 = 0xa0;
const SLAVE_DATA: u16 = 0xa1;

static INITIALIZED: AtomicBool = AtomicBool::new(false);
static TICKS: AtomicU64 = AtomicU64::new(0);

// Each 64-bit gate has the offset split across three fields. The current CS
// selector is reused, so the bootloader's valid long-mode code segment remains
// the destination. IST=0 deliberately keeps the current kernel stack.
#[repr(C)]
#[derive(Clone, Copy)]
struct IdtEntry {
    offset_low: u16,
    selector: u16,
    ist: u8,
    attributes: u8,
    offset_middle: u16,
    offset_high: u32,
    reserved: u32,
}

impl IdtEntry {
    const EMPTY: Self = Self {
        offset_low: 0,
        selector: 0,
        ist: 0,
        attributes: 0,
        offset_middle: 0,
        offset_high: 0,
        reserved: 0,
    };

    fn interrupt_gate(address: usize, selector: u16) -> Self {
        Self {
            offset_low: address as u16,
            selector,
            ist: 0,
            // Present, privilege level 0, 64-bit interrupt gate (type 0xE).
            attributes: 0x8e,
            offset_middle: (address >> 16) as u16,
            offset_high: (address >> 32) as u32,
            reserved: 0,
        }
    }
}

#[repr(align(16))]
struct Idt(UnsafeCell<[IdtEntry; 256]>);

// SAFETY: initialize_timer is the sole writer, runs once with IF=0 on the boot
// CPU and completes the table before lidt. The CPU reads it thereafter. Other
// CPUs may not initialize or mutate it under the public initialization contract.
unsafe impl Sync for Idt {}

static IDT: Idt = Idt(UnsafeCell::new([IdtEntry::EMPTY; 256]));

#[repr(C, packed)]
struct IdtPointer {
    limit: u16,
    base: u64,
}

// These fields match entry.S exactly. Every vector carries an error word,
// either generated by the CPU or supplied as zero by its assembly stub.
#[repr(C)]
struct InterruptFrame {
    saved_registers: [u64; 15],
    vector: u64,
    error: u64,
    instruction_pointer: u64,
    code_segment: u64,
    flags: u64,
    stack_pointer: u64,
    stack_segment: u64,
}

global_asm!(include_str!("entry.S"), dispatcher = sym dispatch_interrupt);

extern "C" {
    static ferrum_interrupt_entries: [i32; 256];
}

/// Reason the boot-CPU timer installation was refused without reconfiguration.
#[derive(Debug, Clone, Copy, Eq, PartialEq)]
pub enum TimerInitError {
    /// Initialization requires maskable interrupts to be disabled first.
    InterruptsEnabled,
    /// The IDT and legacy PIC/PIT have already been claimed by an initializer.
    AlreadyInitialized,
}

/// Install fatal exception handlers and a periodic IRQ0 timer, leaving IF=0.
///
/// The resulting frequency is the exact rational `PIT_INPUT_HZ / PIT_DIVISOR`.
/// Call [`cpu::enable_interrupts`] after the rest of the boot devices are ready.
///
/// # Safety
/// Run once at ring 0 on the only active CPU, with maskable interrupts disabled.
/// The caller exclusively owns the IDT, PIC ports 0x20/0x21/0xA0/0xA1, PIT ports
/// 0x40/0x43 and legacy delay port 0x80. The stack and current long-mode code
/// selector remain valid for the kernel's lifetime. No handler or other CPU
/// may reconfigure these controllers or alter their masks. Code must retain the
/// root target's default absence of AVX/extended state until an XSAVE-aware
/// interrupt entry is supplied. The selected platform routes PIT IRQ0 through
/// the legacy PIC to the boot CPU, as on the supported QEMU PC machine.
pub unsafe fn initialize_timer() -> Result<(), TimerInitError> {
    if cpu::interrupts_enabled() {
        return Err(TimerInitError::InterruptsEnabled);
    }
    INITIALIZED
        .compare_exchange(false, true, Ordering::AcqRel, Ordering::Acquire)
        .map_err(|_| TimerInitError::AlreadyInitialized)?;

    let selector: u16;
    // SAFETY: initialization runs at ring 0 with IF=0. Reading CS identifies
    // the already active long-mode code descriptor without changing it.
    unsafe { asm!("mov {0:x}, cs", out(reg) selector, options(nomem, nostack, preserves_flags)) };
    // SAFETY: the one-time claim above and disabled interrupts give exclusive
    // access. The linked assembly table stores signed offsets from its base,
    // which keeps the entry addresses valid when the bootloader relocates the
    // PIE kernel. The static IDT outlives every installed handler invocation.
    unsafe {
        let entries = &mut *IDT.0.get();
        let table_base = core::ptr::addr_of!(ferrum_interrupt_entries) as usize;
        for (gate, relative) in entries.iter_mut().zip(ferrum_interrupt_entries) {
            let address = table_base.wrapping_add_signed(relative as isize);
            *gate = IdtEntry::interrupt_gate(address, selector);
        }
    }
    let pointer = IdtPointer {
        limit: (size_of::<[IdtEntry; 256]>() - 1) as u16,
        base: IDT.0.get() as u64,
    };
    // SAFETY: pointer describes a completed static table of valid long-mode
    // gates. lidt copies the descriptor and retains the static base address.
    unsafe { asm!("lidt [{}]", in(reg) &pointer, options(readonly, nostack, preserves_flags)) };

    // FXSAVE64 requires CR0.EM/TS clear and CR4.OSFXSR set. x86_64 supplies
    // the baseline FXSAVE/SSE capability. Preserve all unrelated control bits.
    let mut cr0: u64;
    let mut cr4: u64;
    // SAFETY: ring-0 initialization owns CPU setup before handlers can execute.
    unsafe {
        asm!("mov {}, cr0", out(reg) cr0, options(nomem, nostack, preserves_flags));
        asm!("mov {}, cr4", out(reg) cr4, options(nomem, nostack, preserves_flags));
        cr0 = (cr0 & !((1 << 2) | (1 << 3))) | (1 << 1);
        cr4 |= 1 << 9;
        asm!("mov cr0, {}", in(reg) cr0, options(nostack, preserves_flags));
        asm!("mov cr4, {}", in(reg) cr4, options(nostack, preserves_flags));
        configure_pic_and_pit();
    }
    Ok(())
}

/// Number of IRQ0 events actually delivered since timer initialization.
pub fn tick_count() -> u64 {
    TICKS.load(Ordering::Relaxed)
}

/// Capture ticks and their conversions from one atomic observation.
pub fn clock_snapshot() -> TickSnapshot {
    TickSnapshot::new(tick_count(), PIT_INPUT_HZ, PIT_DIVISOR)
        .expect("the configured PIT input clock and divisor are nonzero")
}

unsafe fn write_delayed(port: u16, value: u8) {
    // SAFETY: callers own the PIC/PIT and port 0x80 during initialization.
    // The legacy delay prevents adjacent initialization writes outrunning
    // an 8259-compatible controller on slower PC hardware.
    unsafe {
        write_u8(port, value);
        write_u8(0x80, 0);
    }
}

unsafe fn configure_pic_and_pit() {
    // SAFETY: initialization owns all ports with IF=0. Start fully masked,
    // remap both controllers away from CPU exceptions, then select 8086 mode.
    // The slave remains masked, including its master cascade input IRQ2.
    unsafe {
        write_delayed(MASTER_DATA, 0xff);
        write_delayed(SLAVE_DATA, 0xff);
        write_delayed(MASTER_COMMAND, 0x11);
        write_delayed(SLAVE_COMMAND, 0x11);
        write_delayed(MASTER_DATA, 32);
        write_delayed(SLAVE_DATA, 40);
        write_delayed(MASTER_DATA, 1 << 2);
        write_delayed(SLAVE_DATA, 2);
        write_delayed(MASTER_DATA, 0x01);
        write_delayed(SLAVE_DATA, 0x01);
        write_delayed(MASTER_DATA, 0xff);
        write_delayed(SLAVE_DATA, 0xff);

        // Channel 0, LSB followed by MSB, mode 2 rate generator, binary count.
        write_delayed(0x43, 0x34);
        write_delayed(0x40, PIT_DIVISOR as u8);
        write_delayed(0x40, (PIT_DIVISOR >> 8) as u8);
        // Hardware may queue a timer event now, but IF remains zero until the
        // boot owner has finished initializing every shared device.
        write_delayed(MASTER_DATA, 0xfe);
    }
}

extern "C" fn dispatch_interrupt(frame: &InterruptFrame) {
    if frame.vector == TIMER_VECTOR {
        // Exactly one writer exists: this non-nesting IRQ on the only boot
        // CPU. Atomic storage permits lock-free foreground snapshots. With no
        // competing writer, load/saturating_add/store is bounded and avoids a
        // compare-exchange retry loop in the interrupt path.
        let ticks = TICKS.load(Ordering::Relaxed);
        TICKS.store(ticks.saturating_add(1), Ordering::Relaxed);
        // SAFETY: only IRQ0 is unmasked. It belongs to the master PIC and this
        // handler owns its acknowledgement. No slave EOI is appropriate here.
        unsafe { write_u8(MASTER_COMMAND, 0x20) };
        return;
    }

    // Exception recovery is deliberately terminal in this initial integration.
    // No allocation, formatting to the framebuffer or contested lock occurs.
    // Reinitializing COM1 is valid because normal execution is abandoned.
    let mut fault_address: u64 = 0;
    if frame.vector == 14 {
        // SAFETY: ring-0 page-fault handling may read CR2 for its diagnostic.
        unsafe {
            asm!("mov {}, cr2", out(reg) fault_address, options(nomem, nostack, preserves_flags))
        };
    }
    cpu::disable_interrupts();
    // SAFETY: normal execution is terminal, maskable interrupts are disabled,
    // and no other CPU owns the UART under the initialization contract.
    unsafe {
        crate::drivers::serial::emergency_write(format_args!(
            "\nCPU_EXCEPTION vector={} error={:#x} rip={:#x} cr2={:#x}\n",
            frame.vector, frame.error, frame.instruction_pointer, fault_address
        ));
    }
    cpu::halt_forever()
}
